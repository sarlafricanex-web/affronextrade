-- Tables reprises du site actuel (Neon). Les donnees reelles sont migrees au lancement.

create table public.submissions (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 200),
  email text not null check (char_length(email) <= 320),
  company text check (char_length(company) <= 200),
  country text check (char_length(country) <= 100),
  phone text check (char_length(phone) <= 50),
  whatsapp text check (char_length(whatsapp) <= 50),
  message text check (char_length(message) <= 5000),
  consent boolean not null default true,
  created_at timestamptz not null default now()
);

create index submissions_created_idx on public.submissions (created_at desc);

create table public.reviews (
  id bigint generated by default as identity primary key,
  producer_company_id uuid not null references public.companies (id) on delete cascade,
  legacy_producer_id text,
  author_profile_id uuid references public.profiles (id) on delete set null,
  author_name text not null check (char_length(author_name) between 1 and 100),
  author_company text check (char_length(author_company) <= 100),
  author_country text check (char_length(author_country) <= 100),
  rating smallint not null check (rating between 1 and 5),
  comment text check (char_length(comment) <= 1000),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  moderated_by uuid references public.profiles (id) on delete set null,
  moderated_at timestamptz,
  created_at timestamptz not null default now()
);

create index reviews_company_idx on public.reviews (producer_company_id, created_at desc);
create unique index reviews_one_per_author on public.reviews (producer_company_id, author_profile_id)
  where author_profile_id is not null;
